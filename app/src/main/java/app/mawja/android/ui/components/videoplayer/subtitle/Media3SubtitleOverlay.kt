/**
 * Draws the player's captions with Media3's [SubtitleView], laid out over the picture rather than
 * the whole player, so letterbox bars never separate the two.
 *
 * @param bottomPadding the gap, in dp, between the bottom of the picture and the lowest line.
 * @param resizeMode the player's mode: 0 fit, 1 fill, 2 zoom.
 */
@Composable
fun Media3SubtitleOverlay(
    enabled: Boolean,
    isAutoGenerated: Boolean,
    modifier: Modifier = Modifier,
    style: SubtitleStyle = SubtitleStyle(),
    bottomPadding: Float = style.bottomPadding,
    videoAspectRatio: Float? = null,
    resizeMode: Int = 0,
    secondaryLanguage: String = DualSubtitles.OFF,
    secondaryPosition: SecondSubtitlePosition = SecondSubtitlePosition.ABOVE,
    availableSubtitles: List<SubtitleOption> = emptyList(),
    selectedSubtitleUrl: String? = null,
) {
    var cues by remember { mutableStateOf(emptyList<Cue>()) }
    val player = EnhancedPlayerManager.getInstance().getPlayer()

    DisposableEffect(player) {
        if (player == null) {
            onDispose { }
        } else {
            val listener =
                object : Player.Listener {
                    override fun onCues(cueGroup: CueGroup) {
                        cues = cueGroup.cues
                    }
                }
            player.addListener(listener)
            cues = player.currentCues.cues
            onDispose {
                player.removeListener(listener)
            }
        }
    }

    // Dual subtitles: the second track is fetched on its own and drawn from its timed lines.
    val secondaryUrl =
        remember(enabled, availableSubtitles, selectedSubtitleUrl, secondaryLanguage) {
            if (!enabled) {
                null
            } else {
                DualSubtitles.secondaryTrackUrl(
                    candidates =
                        availableSubtitles.map {
                            CaptionCandidate(it.url, it.language, it.isAutoGenerated, it.isTranslated)
                        },
                    primaryUrl = selectedSubtitleUrl,
                    secondaryLanguage = secondaryLanguage,
                )
            }
        }
    val context = LocalContext.current
    var secondaryCues by remember { mutableStateOf(emptyList<TranscriptCue>()) }
    LaunchedEffect(secondaryUrl) {
        secondaryCues = emptyList()
        val url = secondaryUrl ?: return@LaunchedEffect
        val repository =
            runCatching {
                EntryPointAccessors
                    .fromApplication(context.applicationContext, TranscriptEntryPoint::class.java)
                    .transcriptRepository()
            }.getOrNull() ?: return@LaunchedEffect
        secondaryCues = DualSubtitles.prepared(runCatching { repository.captionCues(url) }.getOrDefault(emptyList()))
    }
    var positionMs by remember { mutableStateOf(0L) }
    LaunchedEffect(player, secondaryCues) {
        if (player == null || secondaryCues.isEmpty()) return@LaunchedEffect
        while (true) {
            positionMs = player.currentPosition
            delay(SECONDARY_POLL_MS)
        }
    }

    if (!enabled) return

    val shownCues = remember(cues, isAutoGenerated) { cues.shown(isAutoGenerated) }
    val primaryText =
        remember(shownCues) {
            shownCues.mapNotNull { it.text?.toString()?.takeIf(String::isNotBlank) }.joinToString("\n").ifBlank { null }
        }
    val secondaryText =
        remember(secondaryCues, positionMs, primaryText) {
            DualSubtitles
                .textAt(secondaryCues, positionMs)
                ?.takeUnless { DualSubtitles.repeatsPrimary(primaryText, it) }
        }

    // Not wrapped in AnimatedVisibility: cues empty out in the gap between every caption, which
    // would tear the SubtitleView down and re-inflate it hundreds of times per video. An empty
    // cue list already draws nothing.
    BoxWithConstraints(modifier = modifier.fillMaxSize()) {
        val area = subtitleArea(maxWidth.value, maxHeight.value, videoAspectRatio, resizeMode)
        // An inset, not SubtitleView's bottom padding fraction: Media3 applies that fraction only
        // to cues without a line of their own, and WebVTT gives every cue one counted up from the
        // bottom, so downloaded and device captions would sit on the edge.
        // Kept short of the picture's top by room for two lines, so the text never leaves it.
        val inset = bottomPadding.coerceIn(0f, (area.height - style.fontSize * LINES_KEPT_IN_VIEW).coerceAtLeast(0f))
        val density = LocalDensity.current
        var secondaryHeightDp by remember { mutableStateOf(0f) }
        val secondaryStyle = remember(style) { style.secondaryTextStyle() }
        val measurer = rememberTextMeasurer()
        val textWidthPx = with(density) { (area.width.dp - SideInset * 2).roundToPx() }.coerceAtLeast(1)
        // Room the primary lines take, so a second line set above them does not cover them.
        val measureAbove = secondaryText != null && secondaryPosition == SecondSubtitlePosition.ABOVE && primaryText != null
        val primaryHeightDp =
            remember(measureAbove, primaryText, textWidthPx, style.fontSize, style.isBold, density) {
                if (!measureAbove || primaryText == null) return@remember 0f
                val measured =
                    measurer.measure(
                        text = primaryText,
                        style = TextStyle(fontSize = style.fontSize.sp, fontWeight = if (style.isBold) FontWeight.Bold else FontWeight.Normal),
                        constraints = Constraints(maxWidth = textWidthPx),
                    )
                with(density) { measured.size.height.toDp().value } + PRIMARY_LINE_PADDING
            }
        val primaryLift =
            if (secondaryText != null && secondaryPosition == SecondSubtitlePosition.BELOW) secondaryHeightDp + SECONDARY_GAP else 0f
        StyledSubtitles(
            cues = shownCues,
            style = style,
            modifier =
                Modifier
                    .offset(area.left.dp, area.top.dp)
                    .size(area.width.dp, area.height.dp)
                    .padding(start = SideInset, end = SideInset, bottom = (inset + primaryLift).dp),
        )
        if (secondaryText != null) {
            val secondaryBottom =
                when (secondaryPosition) {
                    SecondSubtitlePosition.BELOW -> inset
                    SecondSubtitlePosition.ABOVE -> inset + primaryHeightDp + (if (primaryHeightDp > 0f) SECONDARY_GAP else 0f)
                }.coerceAtMost((area.height - style.fontSize * LINES_KEPT_IN_VIEW).coerceAtLeast(0f))
            Box(
                modifier =
                    Modifier
                        .offset(area.left.dp, area.top.dp)
                        .size(area.width.dp, area.height.dp)
                        .padding(start = SideInset, end = SideInset, bottom = secondaryBottom.dp),
                contentAlignment = Alignment.BottomCenter,
            ) {
                Text(
                    text = secondaryText,
                    style = secondaryStyle,
                    textAlign = TextAlign.Center,
                    modifier =
                        Modifier
                            .onSizeChanged { secondaryHeightDp = with(density) { it.height.toDp().value } }
                            .background(style.backgroundColor)
                            .padding(horizontal = 4.dp, vertical = 1.dp),
                )
            }
        }
    }
}

/**
 * The second line's look: the user's caption style, a little smaller and in a warm amber (or white
 * when their own text is already yellow), so the two languages never read as one block.
 */
private fun SubtitleStyle.secondaryTextStyle(): TextStyle {
    val amber = Color(0xFFFFE082)
    val color = if (textColor.isYellowish()) Color.White else amber
    val shadow =
        if (edgeType == SubtitleEdgeType.NONE) {
            null
        } else {
            Shadow(color = edgeColor, offset = Offset(1.5f, 1.5f), blurRadius = 3f)
        }
    return TextStyle(
        color = color,
        fontSize = (fontSize * SECONDARY_SCALE).sp,
        fontWeight = if (isBold) FontWeight.SemiBold else FontWeight.Normal,
        fontFamily =
            when (font) {
                SubtitleFont.SERIF -> FontFamily.Serif
                SubtitleFont.MONOSPACE -> FontFamily.Monospace
                SubtitleFont.SANS_SERIF, SubtitleFont.CONDENSED -> FontFamily.SansSerif
                SubtitleFont.DEFAULT -> FontFamily.Default
            },
        shadow = shadow,
    )
}

private fun Color.isYellowish(): Boolean = red > 0.8f && green > 0.7f && blue < 0.5f

private const val SECONDARY_POLL_MS = 200L
private const val SECONDARY_SCALE = 0.88f
private const val SECONDARY_GAP = 6f
private const val PRIMARY_LINE_PADDING = 6f

/** Media3's [SubtitleView] drawing [cues] in [style], lines stacked up from its bottom edge. */
@Composable
internal fun StyledSubtitles(
    cues: List<Cue>,
    style: SubtitleStyle,
    modifier: Modifier = Modifier,
) {
    val captionStyle = remember(style) { style.toCaptionStyle() }
    AndroidView(
        modifier = modifier,
        factory = { context ->
            SubtitleView(context).apply {
                setApplyEmbeddedStyles(true)
                setApplyEmbeddedFontSizes(false)
                setBottomPaddingFraction(0f)
            }
        },
        update = { view ->
            view.setFixedTextSize(TypedValue.COMPLEX_UNIT_SP, style.fontSize)
            view.setStyle(captionStyle)
            view.setCues(cues)
        },
    )
}

private fun SubtitleStyle.toCaptionStyle(): CaptionStyleCompat =
    CaptionStyleCompat(
        textColor.toArgb(),
        backgroundColor.toArgb(),
        windowColor.toArgb(),
        when (edgeType) {
            SubtitleEdgeType.NONE -> CaptionStyleCompat.EDGE_TYPE_NONE
            SubtitleEdgeType.OUTLINE -> CaptionStyleCompat.EDGE_TYPE_OUTLINE
            SubtitleEdgeType.DROP_SHADOW -> CaptionStyleCompat.EDGE_TYPE_DROP_SHADOW
            SubtitleEdgeType.RAISED -> CaptionStyleCompat.EDGE_TYPE_RAISED
            SubtitleEdgeType.DEPRESSED -> CaptionStyleCompat.EDGE_TYPE_DEPRESSED
        },
        edgeColor.toArgb(),
        Typeface.create(font.familyName, if (isBold) Typeface.BOLD else Typeface.NORMAL),
    )

/**
 * Authored tracks keep their own lines, styling and placement, and image subtitles from device
 * files keep their bitmaps. Speech-recognised tracks are rebuilt into the one latest line.
 */
private fun List<Cue>.shown(isAutoGenerated: Boolean): List<Cue> =
    if (isAutoGenerated) {
        toRollingCaptionText()?.let { listOf(Cue.Builder().setText(it).build()) }.orEmpty()
    } else {
        filter { !it.text.isNullOrBlank() || it.bitmap != null }
    }

private val SideInset = 16.dp
private const val LINES_KEPT_IN_VIEW = 2.5f
