package app.mawja.android.player.subtitle

import app.mawja.android.data.transcript.TranscriptCue
import java.util.Locale

/** Where the second subtitle line sits relative to the primary one. */
enum class SecondSubtitlePosition(
    val key: String,
) {
    ABOVE("above"),
    BELOW("below"),
    ;

    companion object {
        fun of(key: String?): SecondSubtitlePosition = entries.firstOrNull { it.key == key } ?: ABOVE
    }
}

/** What a second subtitle track can be chosen from: one caption track the player offers. */
data class CaptionCandidate(
    val url: String,
    val languageTag: String,
    val isAutoGenerated: Boolean,
    val isTranslated: Boolean,
)

/**
 * Dual subtitles (v1 item 3): the pure part. Media3 renders one text track at a time, so the second
 * track is fetched on its own (one small json3 request through the transcript reader) and drawn
 * beside the primary captions from its timed lines. When the video has no track in the second
 * language, YouTube's machine translation of an authored track is asked for with `tlang`, the same
 * parameter [app.mawja.android.player.stream.CaptionTrackResolver] uses for the primary track.
 */
object DualSubtitles {
    const val OFF = "none"
    private const val TRANSLATE_PARAM = "tlang"
    private const val TIMEDTEXT_MARKER = "timedtext"

    /**
     * The URL of the second track, or null when there is nothing to add: the feature is off, the
     * primary track is off, the primary already is in the second language, or no track can be
     * found or translated (device files and embedded tracks cannot be translated).
     */
    fun secondaryTrackUrl(
        candidates: List<CaptionCandidate>,
        primaryUrl: String?,
        secondaryLanguage: String?,
    ): String? {
        val wanted = secondaryLanguage?.trim()?.takeIf { it.isNotEmpty() && it != OFF } ?: return null
        if (primaryUrl == null) return null
        val primary = candidates.firstOrNull { it.url == primaryUrl }
        if (primary != null && sameLanguage(primary.languageTag, wanted)) return null

        val inLanguage =
            candidates
                .filter { it.url != primaryUrl && sameLanguage(it.languageTag, wanted) }
                .sortedWith(
                    compareBy<CaptionCandidate> { !it.languageTag.equals(wanted, ignoreCase = true) }
                        .thenBy { it.isTranslated }
                        .thenBy { it.isAutoGenerated },
                )
        inLanguage.firstOrNull()?.let { return it.url }

        // Translate the best source: the primary when it is an authored track, then any authored
        // track, then the primary or any track at all (speech recognition translates worse).
        val sources =
            buildList {
                primary?.takeIf { !it.isAutoGenerated && !it.isTranslated }?.let(::add)
                addAll(candidates.filter { !it.isAutoGenerated && !it.isTranslated })
                primary?.let(::add)
                addAll(candidates)
            }
        return sources.firstNotNullOfOrNull { translatedUrl(it.url, wanted) }
    }

    /** [url] with its translation target replaced by [language]; null for a track that is not YouTube's. */
    fun translatedUrl(
        url: String,
        language: String,
    ): String? {
        if (!url.startsWith("https://") || !url.contains(TIMEDTEXT_MARKER)) return null
        val target = language.trim().takeIf { it.isNotEmpty() && it != OFF } ?: return null
        val separator = url.indexOf('?')
        if (separator < 0) return "$url?$TRANSLATE_PARAM=$target"
        val path = url.substring(0, separator)
        val query =
            url
                .substring(separator + 1)
                .split('&')
                .filter { it.isNotEmpty() && !it.startsWith("$TRANSLATE_PARAM=") }
        return "$path?${(query + "$TRANSLATE_PARAM=$target").joinToString("&")}"
    }

    /**
     * The second track's text at [positionMs]: the lines whose time covers it, oldest first, at most
     * [maxLines] (a rolling auto-generated track overlaps its lines). [cues] must be sorted by start.
     */
    fun textAt(
        cues: List<TranscriptCue>,
        positionMs: Long,
        maxLines: Int = 2,
    ): String? {
        if (cues.isEmpty() || maxLines <= 0) return null
        // Last cue that started at or before the position.
        var low = 0
        var high = cues.lastIndex
        var last = -1
        while (low <= high) {
            val mid = (low + high) ushr 1
            if (cues[mid].startMs <= positionMs) {
                last = mid
                low = mid + 1
            } else {
                high = mid - 1
            }
        }
        if (last < 0) return null
        val lines = ArrayDeque<String>()
        var index = last
        // Cues are short; looking back a few is enough to find the overlapping ones.
        while (index >= 0 && last - index < LOOK_BACK && lines.size < maxLines) {
            val cue = cues[index]
            if (positionMs < cue.endMs || (cue.durationMs <= 0L && index == last)) {
                if (lines.none { it == cue.text }) lines.addFirst(cue.text)
            }
            index--
        }
        return lines.takeIf { it.isNotEmpty() }?.joinToString("\n")
    }

    /** Cues in start order with blank ones dropped, the form [textAt] expects. */
    fun prepared(cues: List<TranscriptCue>): List<TranscriptCue> = cues.filter { it.text.isNotBlank() }.sortedBy { it.startMs }

    /** True when the second line would only repeat the primary one (same words, any case or spacing). */
    fun repeatsPrimary(
        primaryText: String?,
        secondaryText: String?,
    ): Boolean {
        if (primaryText.isNullOrBlank() || secondaryText.isNullOrBlank()) return false
        return normalised(primaryText) == normalised(secondaryText)
    }

    fun sameLanguage(
        a: String?,
        b: String?,
    ): Boolean {
        if (a.isNullOrBlank() || b.isNullOrBlank()) return false
        return baseLanguage(a) == baseLanguage(b)
    }

    private fun baseLanguage(tag: String): String =
        tag
            .trim()
            .substringBefore('-')
            .substringBefore('_')
            .lowercase(Locale.ROOT)

    private fun normalised(text: String): String = text.lowercase(Locale.ROOT).replace(WHITESPACE, " ").trim()

    private val WHITESPACE = Regex("\\s+")
    private const val LOOK_BACK = 6
}
