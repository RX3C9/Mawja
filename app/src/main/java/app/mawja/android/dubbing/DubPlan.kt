package app.mawja.android.dubbing

import app.mawja.android.data.transcript.TranscriptCue
import app.mawja.android.player.state.SubtitleOption
import app.mawja.android.player.subtitle.CaptionCandidate
import app.mawja.android.player.subtitle.DualSubtitles

/** How the dub sits on the original sound. */
enum class DubMode(val originalVolume: Float) {
    OFF(1f),

    /** Arabic voice over a quiet original, like a documentary voice-over. */
    VOICE_OVER(0.18f),

    /** Arabic voice only. */
    REPLACE(0f),
}

/** One line to speak: when, what, and how fast so it ends before the next one starts. */
data class DubLine(
    val startMs: Long,
    val endMs: Long,
    val text: String,
    val rate: Float,
)

/**
 * The pure part of Arabic AI dubbing (P3, free tier): pick an Arabic track (authored, YouTube's
 * own auto track, else YouTube's machine translation of the best source), merge caption fragments
 * into speakable sentences, and time each one so speech keeps pace with the video.
 */
object DubPlan {
    const val LANGUAGE = "ar"

    /** Arabic speech by a typical TTS voice at rate 1.0, in characters per second. */
    const val CHARS_PER_SECOND = 14f
    const val MIN_RATE = 0.9f
    const val MAX_RATE = 1.8f
    private const val MERGE_GAP_MS = 350L
    private const val MAX_LINE_MS = 9_000L
    private const val MIN_LINE_MS = 900L

    /** The Arabic caption track URL to dub from, or null when the video has no captions to work with. */
    fun trackUrl(options: List<SubtitleOption>): String? {
        val usable = options.filterNot { it.isForced }
        if (usable.isEmpty()) return null
        val candidates = usable.map { CaptionCandidate(it.url, it.language, it.isAutoGenerated, it.isTranslated) }
        usable
            .filter { DualSubtitles.sameLanguage(it.language, LANGUAGE) }
            .sortedWith(compareBy<SubtitleOption> { it.isTranslated }.thenBy { it.isAutoGenerated })
            .firstOrNull()
            ?.let { return it.url }
        // Any non-Arabic track as the "primary" so the helper looks for, or translates to, Arabic.
        val primary = usable.firstOrNull { !it.isAutoGenerated && !it.isTranslated } ?: usable.first()
        return DualSubtitles.secondaryTrackUrl(candidates, primary.url, LANGUAGE)
    }

    /** Caption fragments joined into lines worth speaking, each with the rate that fits its slot. */
    fun lines(cues: List<TranscriptCue>): List<DubLine> {
        val clean =
            cues
                .map { it.copy(text = it.text.replace(NOISE, " ").replace(SPACES, " ").trim()) }
                .filter { it.text.isNotEmpty() && it.text.any(Char::isLetterOrDigit) }
                .sortedBy { it.startMs }
        val merged = mutableListOf<TranscriptCue>()
        for (cue in clean) {
            val last = merged.lastOrNull()
            val lastEnd = last?.let { end(it) } ?: Long.MIN_VALUE
            val joinable =
                last != null && cue.startMs - lastEnd <= MERGE_GAP_MS && !endsSentence(last.text) &&
                    end(cue) - last.startMs <= MAX_LINE_MS
            if (joinable && last != null) {
                merged[merged.lastIndex] = last.copy(text = last.text + " " + cue.text, durationMs = end(cue) - last.startMs)
            } else if (last != null && last.text == cue.text) {
                continue // rolling auto captions repeat the same words
            } else {
                merged += cue
            }
        }
        return merged.mapIndexed { i, cue ->
            val next = merged.getOrNull(i + 1)?.startMs
            val slotEnd = next?.let { minOf(it, cue.startMs + MAX_LINE_MS) } ?: (cue.startMs + maxOf(cue.durationMs, MIN_LINE_MS))
            val slot = maxOf(slotEnd - cue.startMs, MIN_LINE_MS)
            DubLine(cue.startMs, cue.startMs + slot, cue.text, rateFor(cue.text, slot))
        }
    }

    fun rateFor(
        text: String,
        slotMs: Long,
    ): Float {
        val needed = text.length / CHARS_PER_SECOND * 1000f
        return (needed / slotMs.coerceAtLeast(1)).coerceIn(MIN_RATE, MAX_RATE)
    }

    /** The line playing at [positionMs], or null between lines. */
    fun lineAt(
        lines: List<DubLine>,
        positionMs: Long,
    ): Int? {
        var lo = 0
        var hi = lines.lastIndex
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            val line = lines[mid]
            when {
                positionMs < line.startMs -> hi = mid - 1
                positionMs >= line.endMs -> lo = mid + 1
                else -> return mid
            }
        }
        return null
    }

    private fun end(cue: TranscriptCue) = cue.startMs + cue.durationMs

    private fun endsSentence(text: String) = text.trimEnd().lastOrNull()?.let { it in ".!?؟…" } ?: false

    private val NOISE = Regex("""\[[^\]]*]|\([^)]*(موسيقى|music|تصفيق|applause|ضحك|laughter)[^)]*\)|♪+""", RegexOption.IGNORE_CASE)
    private val SPACES = Regex("""\s+""")
}
