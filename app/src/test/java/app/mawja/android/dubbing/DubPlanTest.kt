package app.mawja.android.dubbing

import app.mawja.android.data.transcript.TranscriptCue
import app.mawja.android.player.state.SubtitleOption
import com.google.common.truth.Truth.assertThat
import org.junit.Test

class DubPlanTest {
    private val yt = "https://www.youtube.com/api/timedtext?v=x&lang="

    @Test
    fun `an authored arabic track wins over translation`() {
        val options =
            listOf(
                SubtitleOption(yt + "en", "en", "English", isAutoGenerated = false),
                SubtitleOption(yt + "ar&kind=asr", "ar", "Arabic (auto)", isAutoGenerated = true),
                SubtitleOption(yt + "ar", "ar", "Arabic", isAutoGenerated = false),
            )
        assertThat(DubPlan.trackUrl(options)).isEqualTo(yt + "ar")
    }

    @Test
    fun `without arabic the best track is machine translated to arabic`() {
        val options =
            listOf(
                SubtitleOption(yt + "en&kind=asr", "en", "English (auto)", isAutoGenerated = true),
                SubtitleOption(yt + "fr", "fr", "French", isAutoGenerated = false),
            )
        val url = DubPlan.trackUrl(options)
        assertThat(url).contains("lang=fr")
        assertThat(url).contains("tlang=ar")
    }

    @Test
    fun `no captions means no dub`() {
        assertThat(DubPlan.trackUrl(emptyList())).isNull()
    }

    @Test
    fun `fragments join into sentences and noise is dropped`() {
        val lines =
            DubPlan.lines(
                listOf(
                    TranscriptCue(0, "[موسيقى]", 1000),
                    TranscriptCue(1000, "أهلاً بكم", 1000),
                    TranscriptCue(2100, "في الحلقة الجديدة.", 1200),
                    TranscriptCue(5000, "اليوم نتكلم عن البحر", 2000),
                ),
            )
        assertThat(lines.map { it.text }).containsExactly("أهلاً بكم في الحلقة الجديدة.", "اليوم نتكلم عن البحر").inOrder()
        assertThat(lines[0].startMs).isEqualTo(1000)
        assertThat(lines[0].endMs).isEqualTo(5000)
    }

    @Test
    fun `repeated rolling captions are spoken once`() {
        val lines = DubPlan.lines(listOf(TranscriptCue(0, "مرحبا.", 800), TranscriptCue(2000, "مرحبا.", 800)))
        assertThat(lines).hasSize(1)
    }

    @Test
    fun `rate speeds up for crowded lines and stays in bounds`() {
        assertThat(DubPlan.rateFor("قصير", 5000)).isEqualTo(DubPlan.MIN_RATE)
        assertThat(DubPlan.rateFor("ا".repeat(28), 1500)).isWithin(0.01f).of(1.333f)
        assertThat(DubPlan.rateFor("ا".repeat(200), 1000)).isEqualTo(DubPlan.MAX_RATE)
    }

    @Test
    fun `line lookup finds the slot under the playhead`() {
        val lines = listOf(DubLine(1000, 3000, "a", 1f), DubLine(4000, 6000, "b", 1f))
        assertThat(DubPlan.lineAt(lines, 500)).isNull()
        assertThat(DubPlan.lineAt(lines, 1000)).isEqualTo(0)
        assertThat(DubPlan.lineAt(lines, 3500)).isNull()
        assertThat(DubPlan.lineAt(lines, 5999)).isEqualTo(1)
        assertThat(DubPlan.lineAt(lines, 6000)).isNull()
    }
}
