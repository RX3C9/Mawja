package app.mawja.android.player.subtitle

import app.mawja.android.data.transcript.TranscriptCue
import app.mawja.android.data.transcript.VideoTranscript
import com.google.common.truth.Truth.assertThat
import org.junit.Test

class DualSubtitlesTest {
    private val base = "https://www.youtube.com/api/timedtext?v=abc&lang=en&fmt=srv3"
    private val en = CaptionCandidate(base, "en", isAutoGenerated = false, isTranslated = false)
    private val enAsr = CaptionCandidate("https://www.youtube.com/api/timedtext?v=abc&lang=en&kind=asr&fmt=vtt", "en", true, false)
    private val arAuthored = CaptionCandidate("https://www.youtube.com/api/timedtext?v=abc&lang=ar&fmt=srv3", "ar", false, false)
    private val arTranslated = CaptionCandidate("$base&tlang=ar", "ar", true, true)

    @Test
    fun `off, no primary, or primary already in that language gives nothing`() {
        assertThat(DualSubtitles.secondaryTrackUrl(listOf(en, arAuthored), en.url, DualSubtitles.OFF)).isNull()
        assertThat(DualSubtitles.secondaryTrackUrl(listOf(en, arAuthored), en.url, "")).isNull()
        assertThat(DualSubtitles.secondaryTrackUrl(listOf(en, arAuthored), null, "ar")).isNull()
        assertThat(DualSubtitles.secondaryTrackUrl(listOf(en, arAuthored), arAuthored.url, "ar-EG")).isNull()
    }

    @Test
    fun `an authored track in the language beats a translated one`() {
        val url = DualSubtitles.secondaryTrackUrl(listOf(en, arTranslated, arAuthored), en.url, "ar")
        assertThat(url).isEqualTo(arAuthored.url)
    }

    @Test
    fun `a translated track already offered is reused`() {
        val url = DualSubtitles.secondaryTrackUrl(listOf(en, arTranslated), en.url, "ar")
        assertThat(url).isEqualTo(arTranslated.url)
    }

    @Test
    fun `without a track in the language the authored primary is translated`() {
        val url = DualSubtitles.secondaryTrackUrl(listOf(enAsr, en), en.url, "ar")
        assertThat(url).isEqualTo("https://www.youtube.com/api/timedtext?v=abc&lang=en&fmt=srv3&tlang=ar")
    }

    @Test
    fun `an auto-generated primary is translated from an authored track when there is one`() {
        val url = DualSubtitles.secondaryTrackUrl(listOf(enAsr, en), enAsr.url, "fr")
        assertThat(url).isEqualTo("$base&tlang=fr")
        val onlyAsr = DualSubtitles.secondaryTrackUrl(listOf(enAsr), enAsr.url, "fr")
        assertThat(onlyAsr).endsWith("&tlang=fr")
        assertThat(onlyAsr).contains("kind=asr")
    }

    @Test
    fun `device files and embedded tracks cannot be translated`() {
        val file = CaptionCandidate("content://media/subs/movie.srt", "en", false, false)
        val embedded = CaptionCandidate("embedded:0", "en", false, false)
        assertThat(DualSubtitles.secondaryTrackUrl(listOf(file, embedded), file.url, "ar")).isNull()
        assertThat(DualSubtitles.translatedUrl("http://www.youtube.com/api/timedtext?v=1", "ar")).isNull()
    }

    @Test
    fun `translated url replaces an earlier target`() {
        assertThat(DualSubtitles.translatedUrl("$base&tlang=de", "ar")).isEqualTo("$base&tlang=ar")
        assertThat(DualSubtitles.translatedUrl("https://www.youtube.com/api/timedtext", "ar"))
            .isEqualTo("https://www.youtube.com/api/timedtext?tlang=ar")
    }

    @Test
    fun `text at a position finds the covering line`() {
        val cues =
            listOf(
                TranscriptCue(1_000, "one", 1_000),
                TranscriptCue(3_000, "two", 1_000),
                TranscriptCue(5_000, "three", 500),
            )
        assertThat(DualSubtitles.textAt(cues, 500)).isNull()
        assertThat(DualSubtitles.textAt(cues, 1_000)).isEqualTo("one")
        assertThat(DualSubtitles.textAt(cues, 1_999)).isEqualTo("one")
        assertThat(DualSubtitles.textAt(cues, 2_500)).isNull()
        assertThat(DualSubtitles.textAt(cues, 3_500)).isEqualTo("two")
        assertThat(DualSubtitles.textAt(cues, 5_400)).isEqualTo("three")
        assertThat(DualSubtitles.textAt(cues, 9_000)).isNull()
        assertThat(DualSubtitles.textAt(emptyList(), 0)).isNull()
    }

    @Test
    fun `overlapping rolling lines show oldest first and at most two`() {
        val cues =
            listOf(
                TranscriptCue(0, "a", 6_000),
                TranscriptCue(1_000, "b", 4_000),
                TranscriptCue(2_000, "c", 3_000),
            )
        assertThat(DualSubtitles.textAt(cues, 2_500)).isEqualTo("b\nc")
        assertThat(DualSubtitles.textAt(cues, 2_500, maxLines = 3)).isEqualTo("a\nb\nc")
    }

    @Test
    fun `prepared sorts by start and drops blank lines`() {
        val prepared = DualSubtitles.prepared(listOf(TranscriptCue(2_000, "b", 1), TranscriptCue(1_000, " ", 1), TranscriptCue(0, "a", 1)))
        assertThat(prepared.map { it.text }).containsExactly("a", "b").inOrder()
    }

    @Test
    fun `a second line that repeats the primary is recognised`() {
        assertThat(DualSubtitles.repeatsPrimary("Hello  world", "hello world")).isTrue()
        assertThat(DualSubtitles.repeatsPrimary("Hello", "مرحبا")).isFalse()
        assertThat(DualSubtitles.repeatsPrimary(null, "x")).isFalse()
    }

    @Test
    fun `languages compare by their base`() {
        assertThat(DualSubtitles.sameLanguage("ar-EG", "ar")).isTrue()
        assertThat(DualSubtitles.sameLanguage("pt_BR", "PT")).isTrue()
        assertThat(DualSubtitles.sameLanguage("en", "ar")).isFalse()
        assertThat(DualSubtitles.sameLanguage("", "ar")).isFalse()
    }

    @Test
    fun `position is read back from its key with above as the default`() {
        assertThat(SecondSubtitlePosition.of("below")).isEqualTo(SecondSubtitlePosition.BELOW)
        assertThat(SecondSubtitlePosition.of("above")).isEqualTo(SecondSubtitlePosition.ABOVE)
        assertThat(SecondSubtitlePosition.of(null)).isEqualTo(SecondSubtitlePosition.ABOVE)
        assertThat(SecondSubtitlePosition.of("sideways")).isEqualTo(SecondSubtitlePosition.ABOVE)
    }

    @Test
    fun `caption parsing keeps each timed line instead of joining sentences`() {
        val json3 =
            """
            {"events":[
              {"tStartMs":0,"dDurationMs":1500,"segs":[{"utf8":"مرحبا"}]},
              {"tStartMs":1500,"dDurationMs":1500,"segs":[{"utf8":"بكم"}]},
              {"tStartMs":1500,"dDurationMs":10,"aAppend":1,"segs":[{"utf8":"\n"}]}
            ]}
            """.trimIndent()
        val cues = VideoTranscript.parseCaptions(json3)
        assertThat(cues.map { it.text }).containsExactly("مرحبا", "بكم").inOrder()
        assertThat(DualSubtitles.textAt(cues, 1_600)).isEqualTo("بكم")
    }
}
